//! Cadenza desktop application (egui/eframe, wgpu renderer).
//!
//! Layers:
//! - [`state`]: [`state::AppState`] and pure editing logic (no window; unit-tested).
//! - [`audio`]: the realtime player on its own thread, polled without blocking.
//! - [`jobs`]: background work (waveform peaks, plugin scans, renders, file dialogs).
//! - [`ui`]: egui views that read the state and call its methods; every edit becomes a
//!   `cadenza_model::Command` through `AppState::apply`.

pub mod audio;
pub mod i18n;
pub mod jobs;
pub mod state;
pub mod theme;
pub mod ui;

use std::path::PathBuf;

pub use ui::CadenzaApp;

#[derive(Debug, thiserror::Error)]
pub enum AppError {
	#[error("could not start the window: {0}")]
	Window(String),
}

/// Window and taskbar icon (generated by `packaging/icons/generate.py`).
const WINDOW_ICON: &[u8] = include_bytes!("../../../packaging/icons/cadenza-256.png");

/// Opens the main window (optionally with a project) and runs until it is closed.
pub fn run(project: Option<PathBuf>) -> Result<(), AppError> {
	#[cfg(target_os = "macos")]
	disable_touch_bar();
	let mut viewport = egui::ViewportBuilder::default()
		.with_title("Cadenza")
		.with_app_id("cadenza")
		.with_inner_size([1480.0, 920.0])
		.with_min_inner_size([960.0, 600.0]);
	if let Ok(icon) = eframe::icon_data::from_png_bytes(WINDOW_ICON) {
		viewport = viewport.with_icon(icon);
	}
	let options = eframe::NativeOptions {
		renderer: eframe::Renderer::Wgpu,
		viewport,
		..Default::default()
	};
	eframe::run_native(
		"Cadenza",
		options,
		Box::new(move |cc| Ok(Box::new(CadenzaApp::new(&cc.egui_ctx, cc.storage, project)))),
	)
	.map_err(|e| AppError::Window(e.to_string()))
}

/// Turns AppKit's Touch Bar support off for this process. The app shows nothing on the
/// Touch Bar, and AppKit's Touch Bar finder can throw while the window is torn down
/// (`_NSTouchBarFinderObservation invalidate`: KVO observer removal), aborting on quit.
/// Must run before the `NSApplication` finishes launching; the registration domain is
/// not persisted.
#[cfg(target_os = "macos")]
fn disable_touch_bar() {
	use objc2::runtime::AnyObject;
	use objc2_foundation::{NSDictionary, NSNumber, NSString, NSUserDefaults, ns_string};

	let off = NSNumber::new_bool(false);
	let defaults: objc2::rc::Retained<NSDictionary<NSString, AnyObject>> =
		NSDictionary::from_slices(&[ns_string!("NSFunctionBarAPIEnabled")], &[&**off]);
	// SAFETY: a dictionary of property-list values, as `registerDefaults:` requires.
	unsafe { NSUserDefaults::standardUserDefaults().registerDefaults(&defaults) };
}

#[cfg(test)]
mod tests {
	#[test]
	fn window_icon_decodes() {
		let icon = eframe::icon_data::from_png_bytes(super::WINDOW_ICON).unwrap();
		assert_eq!((icon.width, icon.height), (256, 256));
	}
}
