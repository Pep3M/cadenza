//! A tiny built-in 8x8 bitmap font for the title strip.
//!
//! XWayland does not ship X11 core fonts by default (Omarchy/Hyprland has
//! none of the classic `misc`/`75dpi` font packages installed, and X core
//! font support is a deprecated, best-effort path in most modern X servers
//! anyway), so drawing the strip's title with `OpenFont`/`QueryFont` would be
//! unreliable. A small embedded bitmap font avoids that dependency entirely:
//! every bit is public-domain pixel data (the classic CP437/`font8x8_basic`
//! glyph set), covering printable ASCII (`0x20..=0x7E`). Characters outside
//! that range (e.g. accented letters in a user's track name) draw as blanks
//! rather than failing.
//!
//! Each glyph is 8 rows of 8 bits; bit `c` (from the LSB) of row `r` is pixel
//! column `c`, row `r`.

