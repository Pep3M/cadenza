/// A codepoint not in the basic ASCII table but common in our UI text (the
/// "—" em dash between device and track names): close enough to a plain
/// hyphen that users will read the title fine.
const EM_DASH_AS_HYPHEN: [u8; 8] = [0x00, 0x00, 0x00, 0x3F, 0x00, 0x00, 0x00, 0x00];

/// The 8x8 bitmap for `ch` (row-major, bit `c` from the LSB = column `c`).
/// Codepoints we have no glyph for (accented letters, CJK, emoji...) draw as
/// blank space rather than failing: the strip always stays legible for the
/// part it can render.
pub(crate) fn glyph(ch: char) -> [u8; 8] {
	if ch == '—' || ch == '–' {
		return EM_DASH_AS_HYPHEN;
	}
	let code = ch as u32;
	if (FIRST as u32..=LAST as u32).contains(&code) {
		GLYPHS[(code - FIRST as u32) as usize]
	} else {
		GLYPHS[0]
	}
}

/// Pixel width of one glyph cell, including the space between characters.
pub(crate) const GLYPH_WIDTH: u32 = 8;
pub(crate) const GLYPH_HEIGHT: u32 = 8;

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn known_ascii_round_trips() {
		assert_eq!(glyph(' '), [0u8; 8]);
		assert_eq!(glyph('A'), [0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]);
		assert_eq!(glyph('z'), [0x00, 0x00, 0x3F, 0x19, 0x0C, 0x26, 0x3F, 0x00]);
		assert_eq!(glyph('~'), [0x6E, 0x3B, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);
	}

	#[test]
	fn em_dash_falls_back_to_a_hyphen_shape() {
		assert_eq!(glyph('—'), EM_DASH_AS_HYPHEN);
	}

	#[test]
	fn unknown_codepoints_are_blank_not_a_panic() {
		assert_eq!(glyph('é'), [0u8; 8]);
		assert_eq!(glyph('漢'), [0u8; 8]);
	}
}
